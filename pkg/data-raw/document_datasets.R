# Generate pkg/R/data.R from the test-type registry and the written csv files.
#
# The dataset documentation is generated rather than hand-written so that it
# cannot fall out of step with the data. Run after generate_datasets.R.

pkg_root <- if (basename(getwd()) == "pkg") "." else "pkg"
source(file.path(pkg_root, "R", "test_types.R"))

reg <- cr_test_types()

# Column meanings that are shared across test types. Anything not listed is
# described from the registry row.
common <- c(
  conc = "Nominal exposure concentration, in the units given below. Zero is the control.",
  replicate = "Replicate identifier within concentration.",
  immobile = "Individuals immobilised, as recorded on the bench sheet. The analysis uses its complement, `mobile`, so that the response declines with concentration."
)

block <- function(r) {
  d <- utils::read.csv(file.path(pkg_root, "inst", "extdata", paste0(r$id, ".csv")))
  descr <- vapply(names(d), function(cn) {
    if (cn %in% names(common)) {
      return(common[[cn]])
    }
    if (!is.na(r$trials_var) && cn == r$trials_var) {
      return("Number of individuals exposed in the replicate.")
    }
    if (cn == r$y_var) {
      return(paste0("Response: ", r$endpoint, "."))
    }
    cn
  }, character(1))

  c(
    paste0("#' ", r$label),
    "#'",
    paste0("#' Simulated example data for the `", r$id, "` test type, with a design ",
           "following ", r$guideline, ". Concentrations are in ", r$conc_units, "."),
    "#'",
    paste0("#' @format A data frame with ", nrow(d), " rows and ", ncol(d), " columns:"),
    "#' \\describe{",
    paste0("#'   \\item{", names(d), "}{", descr, "}"),
    "#' }",
    "#' @source Simulated by `data-raw/generate_datasets.R`. The parameters used",
    "#'   to generate the data are stored in the `truth` attribute of the object,",
    "#'   so that a fitted estimate can be compared against the value that",
    "#'   produced it.",
    paste0('"', r$id, '"'),
    ""
  )
}

lines <- c(
  "# Dataset documentation, generated by data-raw/document_datasets.R.",
  "# Do not edit by hand: edit the registry in test_types.R or the generator,",
  "# then re-run that script.",
  "",
  unlist(lapply(seq_len(nrow(reg)), function(i) block(reg[i, , drop = FALSE])))
)

# LF on every platform, so that running this on Windows and on Linux produces
# the same file rather than one that differs only in its line endings.
con <- file(file.path(pkg_root, "R", "data.R"), open = "wb")
writeLines(lines, con, sep = "\n")
close(con)
message("wrote R/data.R (", length(lines), " lines)")
